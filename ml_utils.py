"""Data validation and model evaluation shared by the app and verification script."""
from collections import OrderedDict

import numpy as np
import pandas as pd
from sklearn.metrics import (
    accuracy_score,
    confusion_matrix,
    f1_score,
    matthews_corrcoef,
    precision_score,
    recall_score,
    roc_auc_score,
)

FEATURES = [f"feature_{n:02d}" for n in range(1, 42)]
TARGET = "target"
CLASS_ORDER = ["NRB", "RB"]
POSITIVE_CLASS = "RB"
TRAINING_SKLEARN_VERSION = "1.9.1"

MODEL_FILES = OrderedDict([
    ("Logistic Regression", "logistic_regression.joblib"),
    ("Decision Tree", "decision_tree.joblib"),
    ("KNN", "knn.joblib"),
    ("Naive Bayes", "naive_bayes.joblib"),
    ("Support Vector Machine", "svm.joblib"),
])

METRIC_NAMES = ["Accuracy", "AUC", "Precision", "Recall", "F1", "MCC"]


class DataValidationError(ValueError):
    """The uploaded data does not match the model's expected CSV format."""


def validate_test_data(data: pd.DataFrame):
    """Return (X, y, extra_columns) after checking the 41 input features and target."""
    if data.empty:
        raise DataValidationError("The uploaded CSV has no data rows.")
    if data.columns.duplicated().any():
        raise DataValidationError("The CSV contains repeated column names.")

    required = FEATURES + [TARGET]
    missing = [column for column in required if column not in data.columns]
    if missing:
        first_few = ", ".join(missing[:8])
        extra_note = "..." if len(missing) > 8 else ""
        raise DataValidationError(
            f"Missing required columns: {first_few}{extra_note}. "
            "Use the test_data.csv generated by the notebook."
        )

    extras = [column for column in data.columns if column not in required]
    X = data.loc[:, FEATURES].apply(pd.to_numeric, errors="coerce")
    if X.isna().any().any():
        bad = X.columns[X.isna().any()].tolist()
        raise DataValidationError(
            "Input features contain blanks or nonnumeric values in: "
            + ", ".join(bad[:6])
        )
    if not np.isfinite(X.to_numpy(dtype="float64")).all():
        raise DataValidationError("Input features must contain only finite numbers.")

    y = data[TARGET].astype("string").str.strip()
    if y.isna().any() or not y.isin(CLASS_ORDER).all():
        raise DataValidationError("The target column must contain only NRB or RB.")

    return X.astype("float64"), y.astype(str), extras


def evaluate_model(model, X: pd.DataFrame, y: pd.Series):
    """Evaluate a fitted classifier without altering or refitting it."""
    class_names = list(model.classes_)
    if POSITIVE_CLASS not in class_names:
        raise ValueError(f"Saved model has unexpected classes: {class_names}")
    if not hasattr(model, "predict_proba"):
        raise ValueError("This saved model does not support probability predictions.")

    predictions = model.predict(X)
    positive_index = class_names.index(POSITIVE_CLASS)
    probabilities = model.predict_proba(X)[:, positive_index]

    # AUC is undefined if the uploaded test file only contains one class.
    auc = float("nan")
    if y.nunique() == 2:
        auc = roc_auc_score((y == POSITIVE_CLASS).astype(int), probabilities)

    metrics = {
        "Accuracy": accuracy_score(y, predictions),
        "AUC": auc,
        "Precision": precision_score(y, predictions, pos_label=POSITIVE_CLASS, zero_division=0),
        "Recall": recall_score(y, predictions, pos_label=POSITIVE_CLASS, zero_division=0),
        "F1": f1_score(y, predictions, pos_label=POSITIVE_CLASS, zero_division=0),
        "MCC": matthews_corrcoef(y, predictions),
    }
    matrix = confusion_matrix(y, predictions, labels=CLASS_ORDER)
    return metrics, predictions, matrix
